import type { PokemonType } from './types';

/**
 * こうかばつぐんになる相手のタイプ（docs/SPEC.md §3.5）。
 * 「いまひとつ」「こうかがない」は、園児の体験を損なうため実装しない。
 */
export const TYPE_CHART: Record<PokemonType, readonly PokemonType[]> = {
  ノーマル: [],
  ほのお: ['くさ', 'こおり', 'むし', 'はがね'],
  みず: ['ほのお', 'じめん', 'いわ'],
  でんき: ['みず', 'ひこう'],
  くさ: ['みず', 'じめん', 'いわ'],
  こおり: ['くさ', 'じめん', 'ひこう', 'ドラゴン'],
  かくとう: ['ノーマル', 'こおり', 'いわ', 'あく', 'はがね'],
  どく: ['くさ', 'フェアリー'],
  じめん: ['ほのお', 'でんき', 'どく', 'いわ', 'はがね'],
  ひこう: ['くさ', 'かくとう', 'むし'],
  エスパー: ['かくとう', 'どく'],
  むし: ['くさ', 'エスパー', 'あく'],
  いわ: ['ほのお', 'こおり', 'ひこう', 'むし'],
  ゴースト: ['エスパー', 'ゴースト'],
  ドラゴン: ['ドラゴン'],
  あく: ['エスパー', 'ゴースト'],
  はがね: ['こおり', 'いわ', 'フェアリー'],
  フェアリー: ['かくとう', 'ドラゴン', 'あく'],
};

export function isSuperEffective(attackType: PokemonType, targetType: PokemonType): boolean {
  return TYPE_CHART[attackType].includes(targetType);
}
